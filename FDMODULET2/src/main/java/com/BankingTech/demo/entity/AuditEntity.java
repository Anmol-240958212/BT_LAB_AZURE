package com.BankingTech.demo.entity;

import jakarta.persistence.Column;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;

import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.UUID;

@MappedSuperclass
public abstract class AuditEntity {

    /*
     * CRUD / operation indicator.
     *
     * The actual database column name is overridden
     * by each entity.
     */
    @Column(name = "crud_value")
    private String crudValue;

    /*
     * User responsible for the operation.
     */
    @Column(name = "user_id")
    private String userId;

    /*
     * Workstation / system identifier.
     */
    @Column(name = "ws_id")
    private String wsId;

    /*
     * Timestamp generated by the host system.
     */
    @Column(name = "host_ts")
    private LocalDateTime hostTs;

    /*
     * Local system timestamp.
     */
    @Column(name = "local_ts")
    private LocalDateTime localTs;

    /*
     * Rule / system identifier associated
     * with the operation.
     */
    @Column(name = "rule_system_id")
    private String ruleSystemId;

    /*
     * Acceptance timestamp.
     */
    @Column(name = "acpt_ts")
    private LocalDateTime acptTs;

    /*
     * UTC offset associated with acceptance timestamp.
     */
    @Column(name = "acpt_ts_utc_ofst")
    private String acptTsUtcOfst;

    /*
     * Unique identifier for the record.
     */
    @Column(name = "uuid")
    private UUID uuid;

    public String getCrudValue() {
        return crudValue;
    }

    public void setCrudValue(String crudValue) {
        this.crudValue = crudValue;
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getWsId() {
        return wsId;
    }

    public void setWsId(String wsId) {
        this.wsId = wsId;
    }

    public LocalDateTime getHostTs() {
        return hostTs;
    }

    public void setHostTs(LocalDateTime hostTs) {
        this.hostTs = hostTs;
    }

    public LocalDateTime getLocalTs() {
        return localTs;
    }

    public void setLocalTs(LocalDateTime localTs) {
        this.localTs = localTs;
    }

    public String getRuleSystemId() {
        return ruleSystemId;
    }

    public void setRuleSystemId(String ruleSystemId) {
        this.ruleSystemId = ruleSystemId;
    }

    public LocalDateTime getAcptTs() {
        return acptTs;
    }

    public void setAcptTs(LocalDateTime acptTs) {
        this.acptTs = acptTs;
    }

    public String getAcptTsUtcOfst() {
        return acptTsUtcOfst;
    }

    public void setAcptTsUtcOfst(String acptTsUtcOfst) {
        this.acptTsUtcOfst = acptTsUtcOfst;
    }

    public UUID getUuid() {
        return uuid;
    }

    public void setUuid(UUID uuid) {
        this.uuid = uuid;
    }

    /**
     * Guarantees that every FD-owned row has a complete audit trail, including
     * rows created by Kafka consumers and batch jobs where no browser user is
     * available. Explicit values supplied by a business service are preserved.
     */
    @PrePersist
    protected void populateAuditFieldsOnCreate() {
        LocalDateTime now = LocalDateTime.now();
        if (crudValue == null || crudValue.isBlank()) crudValue = "CREATE";
        if (userId == null || userId.isBlank()) userId = "SYSTEM";
        if (wsId == null || wsId.isBlank()) wsId = "FD_MODULE";
        if (ruleSystemId == null || ruleSystemId.isBlank()) ruleSystemId = getClass().getSimpleName();
        if (hostTs == null) hostTs = now;
        if (localTs == null) localTs = now;
        if (acptTs == null) acptTs = now;
        if (acptTsUtcOfst == null || acptTsUtcOfst.isBlank()) {
            acptTsUtcOfst = ZoneOffset.systemDefault().getRules().getOffset(now).toString();
        }
        if (uuid == null) uuid = UUID.randomUUID();
    }

    /** Records the most recent persistence operation without losing its immutable correlation UUID. */
    @PreUpdate
    protected void populateAuditFieldsOnUpdate() {
        LocalDateTime now = LocalDateTime.now();
        crudValue = "UPDATE";
        hostTs = now;
        localTs = now;
        acptTs = now;
        if (userId == null || userId.isBlank()) userId = "SYSTEM";
        if (wsId == null || wsId.isBlank()) wsId = "FD_MODULE";
        if (ruleSystemId == null || ruleSystemId.isBlank()) ruleSystemId = getClass().getSimpleName();
        if (acptTsUtcOfst == null || acptTsUtcOfst.isBlank()) {
            acptTsUtcOfst = ZoneOffset.systemDefault().getRules().getOffset(now).toString();
        }
        if (uuid == null) uuid = UUID.randomUUID();
    }
}
