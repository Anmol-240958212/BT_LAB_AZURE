package com.BankingTech.demo.controller;

import com.BankingTech.demo.dto.requestdto.FDTransactionRequestDTO;
import com.BankingTech.demo.dto.responsedto.FDTransactionLedgerEntryDTO;
import com.BankingTech.demo.entity.FDTransactionEntity;
import com.BankingTech.demo.repository.FDTransactionRepository;
import com.BankingTech.demo.repository.FixedDepositAccountRepository;
import com.BankingTech.demo.service.FDTransactionService;
import com.BankingTech.demo.service.FdRoleAuthorization;

import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/fd/transactions")
public class FDTransactionController {

    private final FDTransactionService fdTransactionService;
    private final FdRoleAuthorization roleAuthorization;
    private final FDTransactionRepository transactions;
    private final FixedDepositAccountRepository accounts;

    public FDTransactionController(
            FDTransactionService fdTransactionService, FdRoleAuthorization roleAuthorization,
            FDTransactionRepository transactions, FixedDepositAccountRepository accounts) {
        this.fdTransactionService = fdTransactionService;
        this.roleAuthorization = roleAuthorization;
        this.transactions = transactions;
        this.accounts = accounts;
    }

    @PostMapping
    public ResponseEntity<String> createTransaction(
            @RequestBody FDTransactionRequestDTO request,
            @RequestHeader(value = "Authorization", required = false) String authorization) {

        roleAuthorization.requireStaffOperation(authorization);

        fdTransactionService.recordTransaction(
                request.getFdAccountNo(),
                request.getTxnType(),
                request.getAmount(),
                request.getPenaltyAmount(),
                request.getTxnDate(),
                request.getRemarks());

        return ResponseEntity.ok(
                "FD transaction recorded successfully");
    }

    /**
     * Administrative, read-only ledger. Financial transactions are generated by
     * account opening, interest, withdrawal, and maturity workflows; this endpoint
     * never creates or modifies a transaction.
     */
    @GetMapping
    public ResponseEntity<List<FDTransactionLedgerEntryDTO>> ledger(
            @RequestParam(value = "accountNo", required = false) String accountNo,
            @RequestHeader(value = "Authorization", required = false) String authorization) {
        roleAuthorization.requireAdmin(authorization);

        Map<String, com.BankingTech.demo.entity.FixedDepositAccountEntity> accountByNumber = accounts.findAll().stream()
                .collect(Collectors.toMap(com.BankingTech.demo.entity.FixedDepositAccountEntity::getFdAccountNo, account -> account));
        List<FDTransactionEntity> entries = accountNo == null || accountNo.isBlank()
                ? transactions.findAllByOrderByFdTransactionTxnDateDesc()
                : transactions.findByFdTransactionFdAccountNoOrderByFdTransactionTxnDateDesc(accountNo.trim());

        return ResponseEntity.ok(entries.stream().map(entry -> ledgerEntry(entry, accountByNumber.get(entry.getFdTransactionFdAccountNo())))
                .toList());
    }

    private FDTransactionLedgerEntryDTO ledgerEntry(FDTransactionEntity entry,
            com.BankingTech.demo.entity.FixedDepositAccountEntity account) {
        return new FDTransactionLedgerEntryDTO(entry.getFdTransactionId(), entry.getFdTransactionFdAccountNo(),
                account == null ? null : account.getFdAccountCustomerId(),
                account == null || account.getFdAccountCurrency() == null ? "INR" : account.getFdAccountCurrency(),
                entry.getFdTransactionTxnType(), entry.getFdTransactionAmount(),
                entry.getFdTransactionPenaltyAmount() == null ? BigDecimal.ZERO : entry.getFdTransactionPenaltyAmount(),
                entry.getFdTransactionTxnDate(), entry.getFdTransactionRemarks());
    }
}
